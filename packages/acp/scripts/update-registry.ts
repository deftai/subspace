/**
 * Refresh the bundled snapshot of the ACP agent registry:
 *   pnpm --filter @deft-subspace/acp run registry:update
 * Writes src/registry-snapshot.ts from
 * https://cdn.agentclientprotocol.com/registry/v1/latest/registry.json,
 * keeping the fields Subspace uses (no icons).
 */
import { writeFile } from 'node:fs/promises';
import { REGISTRY_URL, trimRegistry } from '../src/registry.ts';

const response = await fetch(REGISTRY_URL);
if (!response.ok) throw new Error(`${REGISTRY_URL}: HTTP ${response.status}`);
const registry = trimRegistry(await response.json());
const file = new URL('../src/registry-snapshot.ts', import.meta.url);
await writeFile(
  file,
  `/**\n * The ACP agent registry, as of ${new Date().toISOString().slice(0, 10)} (${registry.agents.length} agents).\n * Generated by scripts/update-registry.ts from ${REGISTRY_URL}; do not edit.\n */\nimport type { Registry } from './registry.ts';\n\nexport const REGISTRY_SNAPSHOT_DATE = '${new Date().toISOString().slice(0, 10)}';\n\nexport const REGISTRY_SNAPSHOT: Registry = ${JSON.stringify(registry, null, 2)};\n`
);
console.log(`${registry.agents.length} agents -> ${file.pathname}`);
